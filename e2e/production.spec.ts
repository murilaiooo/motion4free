import { expect, test } from '@playwright/test';
import { ALL_FORMATS, FilePathSource, Input } from 'mediabunny';

test('creative setup produces an edited draft, preserves preferences and exports the chosen format', async ({ page }, info) => {
  await page.goto('/');
  await page.getByTestId('start-creative').click();
  await page.getByRole('button', { name: 'YouTube', exact: true }).click();
  await page.getByTestId('setup-next').click();
  await page.getByRole('button', { name: 'Sem cortes', exact: true }).click();
  await page.getByTestId('setup-next').click();
  await page.getByTestId('setup-next').click();
  await page.getByRole('button', { name: 'Documental', exact: true }).click();
  await page.getByTestId('setup-next').click();
  await page.getByTestId('setup-next').click();
  await page.getByText('Ajustes opcionais', { exact: true }).click();
  await page.getByText('Abertura e chamada final', { exact: true }).click();
  await page.getByRole('button', { name: 'Salve para ver depois', exact: true }).click();
  await page.screenshot({ path: info.outputPath('creative-setup.png'), fullPage: true });
  await page.getByTestId('setup-complete').click();
  await expect(page.getByTestId('upload-brief')).toContainText('16:9');
  await page.getByTestId('production-file-input').setInputFiles('e2e/fixtures/fala-com-pausas.webm');
  await expect(page.getByTestId('draft-review')).toBeVisible({ timeout: 60_000 });
  await expect(page.getByTestId('out-duration')).toContainText('6.0');
  await expect(page.getByTestId('draft-review')).toContainText('Documental');
  await page.screenshot({ path: info.outputPath('first-draft.png') });
  await page.getByTestId('draft-export').click();
  const download = page.getByTestId('download');
  await expect(download).toBeVisible({ timeout: 90_000 });
  const [file] = await Promise.all([page.waitForEvent('download'), download.click()]);
  const path = info.outputPath('production-horizontal.mp4');
  await file.saveAs(path);
  const media = new Input({ source: new FilePathSource(path), formats: ALL_FORMATS });
  const video = await media.getPrimaryVideoTrack();
  expect(video?.displayWidth).toBe(1920);
  expect(video?.displayHeight).toBe(1080);
  expect((await media.getPrimaryAudioTrack())?.codec).toBe('aac');
  expect(await media.computeDuration()).toBeCloseTo(6, 0);
  media.dispose();
  await page.getByRole('button', { name: 'Fechar', exact: true }).click();
  await page.getByTestId('draft-customize').click();
  await expect(page.getByTestId('draft-review')).toHaveCount(0);
  await expect(page.getByTestId('timeline')).toBeVisible();
  await page.reload();
  await expect(page.getByTestId('player-canvas')).toBeVisible({ timeout: 30_000 });
  await expect(page.getByTestId('out-duration')).toContainText('6.0');
});

test('optional setup can be skipped, revisited and recovered without uploading media', async ({ page }) => {
  await page.goto('/');
  await page.getByTestId('start-creative').click();
  await page.getByRole('button', { name: 'TikTok', exact: true }).click();
  await page.getByTestId('setup-next').click();
  await page.reload();
  await page.getByTestId('start-creative').click();
  await expect(page.getByRole('button', { name: 'TikTok', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByTestId('setup-skip').click();
  await expect(page.getByTestId('upload-brief')).toBeVisible();
  await page.getByRole('button', { name: 'Rever escolhas' }).click();
  await expect(page.getByRole('button', { name: 'TikTok', exact: true })).toHaveAttribute('aria-pressed', 'true');
});

test('direction revision preserves manual text, timeline and undo history', async ({ page }) => {
  await page.goto('/');
  await page.getByTestId('file-input').setInputFiles('e2e/fixtures/fala-com-pausas.webm');
  await expect(page.getByTestId('draft-review')).toBeVisible({ timeout: 60_000 });
  await page.getByTestId('draft-customize').click();
  await page.getByRole('tab', { name: 'Texto', exact: true }).click();
  await page.getByTestId('add-text-texto').click();
  await expect.poll(() => page.evaluate(() => (window as any).__m4f.plan.edits.added.length)).toBe(1);
  const before = await page.evaluate(() => JSON.stringify((window as any).__m4f.plan));
  await page.getByRole('button', { name: 'Direção criativa', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Etapas da configuração' }).getByRole('button', { name: 'Edição', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Visual', exact: true }).click();
  await page.getByRole('button', { name: 'Documental', exact: true }).click();
  await page.getByTestId('setup-skip').click();
  await expect(page.getByTestId('draft-review')).toContainText('Documental');
  expect(await page.evaluate(() => (window as any).__m4f.history.past.length)).toBe(2);
  expect(await page.evaluate(() => (window as any).__m4f.plan.edits.added[0].text)).toBe('Seu texto aqui');
  await page.getByTestId('undo').click();
  expect(await page.evaluate(() => JSON.stringify((window as any).__m4f.plan))).toBe(before);
});
